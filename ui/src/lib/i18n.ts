export const locale = navigator.language.toLowerCase().startsWith("es") ? "es" : "en";
const dict: Record<Key, string> = locale === "es" ? es : en;
document.documentElement.lang = locale;

/** `t` with `{name}` placeholders filled in. */
export function tf(key: Key, vars: Record<string, string | number>): string {
  return t(key).replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""));
}

const sizeUnits = locale === "es" ? ["B", "KB", "MB", "GB"] : ["B", "KB", "MB", "GB"];

export function bytes(n: number): string {
  let v = n;
  let i = 0;
  while (v >= 1000 && i < sizeUnits.length - 1) {
    v /= 1000;
    i++;
  }
  return `${v.toLocaleString(locale, { maximumFractionDigits: v < 10 && i > 0 ? 1 : 0 })} ${sizeUnits[i]}`;
}

export function duration(sec: number): string {
  const s = Math.max(0, Math.round(sec));
  return `${Math.floor(s / 60)}:${String(s % 60).padStart(2, "0")}`;
}

export function t(key: Key): string {
  return dict[key];
}

const timeFmt = new Intl.DateTimeFormat(locale, { hour: "numeric", minute: "2-digit" });
const dayFmt = new Intl.DateTimeFormat(locale, { day: "numeric", month: "short" });
const longDayFmt = new Intl.DateTimeFormat(locale, { weekday: "long", day: "numeric", month: "long" });

function startOfDay(d: Date): number {
  return new Date(d.getFullYear(), d.getMonth(), d.getDate()).getTime();
}

function daysAgo(ts: number): number {
  return Math.round((startOfDay(new Date()) - startOfDay(new Date(ts * 1000))) / 86_400_000);
}

export function time(ts: number): string {
  return timeFmt.format(new Date(ts * 1000));
}

/** Compact stamp for the chat list: time today, otherwise the date. */
export function stamp(ts: number): string {
  if (!ts) return "";
  const ago = daysAgo(ts);
  if (ago <= 0) return time(ts);
  if (ago === 1) return t("day.yesterday");
  return dayFmt.format(new Date(ts * 1000));
}

export function dayLabel(ts: number): string {
  const ago = daysAgo(ts);
  if (ago <= 0) return t("day.today");
  if (ago === 1) return t("day.yesterday");
  return longDayFmt.format(new Date(ts * 1000));
}

export function dayKey(ts: number): number {
  return startOfDay(new Date(ts * 1000));
}
